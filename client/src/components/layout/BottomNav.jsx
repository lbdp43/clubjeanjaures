import { NavLink } from 'react-router-dom';
import { useAuth } from '../../hooks/useAuth';

const navItems = [
  { to: '/', label: 'Accueil', icon: HomeIcon },
  { to: '/annuaire', label: 'Annuaire', icon: UsersIcon },
  { to: '/agenda', label: 'Agenda', icon: CalendarIcon },
  { to: '/profil', label: 'Profil', icon: ProfileIcon, auth: true },
  { to: '/admin', label: 'Admin', icon: AdminIcon, admin: true }
];

export default function BottomNav() {
  const { user, isAdmin } = useAuth();

  const items = navItems.filter(item => {
    if (item.admin) return isAdmin;
    if (!item.auth) return true;
    if (item.showForVisitor && user) return true;
    return !!user;
  });

  return (
    <nav role="navigation" aria-label="Navigation principale" className="lg:hidden fixed bottom-0 left-0 right-0 bg-white border-t border-gray-100 flex justify-around py-2 z-40 safe-bottom">
      {items.map(({ to, label, icon: Icon }) => (
        <NavLink
          key={to}
          to={to}
          end={to === '/'}
          aria-label={label}
          className={({ isActive }) =>
            `flex flex-col items-center gap-0.5 px-1.5 py-1 text-[10px] sm:text-xs transition-colors ${
              isActive ? 'text-blue' : 'text-text-muted'
            }`
          }
        >
          <Icon />
          <span>{label}</span>
        </NavLink>
      ))}
    </nav>
  );
}

